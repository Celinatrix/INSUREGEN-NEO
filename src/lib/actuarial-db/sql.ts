// Sinh DDL Postgres từ sổ đăng ký 73 dataset. Dùng bởi scripts/gen-actuarial-migration.ts
// và test (bảo đảm file migration luôn khớp sổ đăng ký).
import type { DatasetDef, Field } from "./types.ts";
import { DATASETS, DATASET_BY_ID } from "./registry.ts";

const SQL_TYPE: Record<Field["type"], string> = {
  integer: "integer",
  numeric: "numeric",
  probability: "numeric",
  rate: "numeric",
  money: "numeric(20,2)",
  currency: "char(3)",
  text: "text",
  date: "date",
  timestamp: "timestamptz",
  boolean: "boolean",
  json: "jsonb",
};

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

function column(field: Field): string {
  const checks: string[] = [];
  if (field.type === "probability") checks.push(`${field.name} between 0 and 1`);
  if (field.type === "rate") checks.push(`${field.name} between -1 and 10`);
  if (field.allowed) checks.push(`${field.name} in (${field.allowed.map(q).join(", ")})`);
  if (field.min !== undefined) checks.push(`${field.name} >= ${field.min}`);
  if (field.max !== undefined) checks.push(`${field.name} <= ${field.max}`);
  const check = checks.length ? ` check (${checks.join(" and ")})` : "";
  return `  ${field.name} ${SQL_TYPE[field.type]}${field.required ? " not null" : ""}${check}`;
}

/** Thứ tự tạo bảng sao cho bảng được tham chiếu luôn đứng trước. */
export function creationOrder(defs: DatasetDef[] = DATASETS): DatasetDef[] {
  const out: DatasetDef[] = [];
  const done = new Set<string>();
  const visit = (x: DatasetDef, stack: Set<string>) => {
    if (done.has(x.id)) return;
    if (stack.has(x.id)) throw new Error(`foreign key cycle at ${x.id}`);
    stack.add(x.id);
    for (const k of x.foreignKeys) if (k.references.dataset !== x.id) visit(DATASET_BY_ID.get(k.references.dataset)!, stack);
    stack.delete(x.id);
    done.add(x.id);
    out.push(x);
  };
  for (const x of defs) visit(x, new Set());
  return out;
}

export function tableDdl(x: DatasetDef): string {
  const lines = [
    ...x.fields.map(column),
    // Cột quản trị chung cho mọi dataset (yêu cầu: nguồn, chất lượng, phiên bản, thời điểm).
    `  data_quality text not null default ${q(x.quality)} check (data_quality in ('verified', 'transcribed', 'report', 'computed', 'operational', 'missing', 'synthetic'))`,
    "  record_version integer not null default 1 check (record_version >= 1)",
    "  created_at timestamptz not null default now()",
    "  updated_at timestamptz not null default now()",
    `  primary key (${x.primaryKey.join(", ")})`,
    ...x.foreignKeys.map((k) => {
      const ref = DATASET_BY_ID.get(k.references.dataset)!;
      return `  foreign key (${k.fields.join(", ")}) references public.${ref.table} (${k.references.fields.join(", ")})`;
    }),
  ];
  return [
    `-- ${x.id} ${x.name} (group ${x.group}, v${x.version})`,
    `create table if not exists public.${x.table} (\n${lines.join(",\n")}\n);`,
    `comment on table public.${x.table} is ${q(`${x.id}: ${x.description} Source: ${x.source}`)};`,
    `alter table public.${x.table} enable row level security;`,
  ].join("\n");
}

export function migrationSql(): string {
  const ordered = creationOrder();
  const registryRows = DATASETS.map(
    (x) => `  (${q(x.id)}, ${q(x.table)}, ${q(x.name)}, ${q(x.group)}, ${q(x.version)}, ${q(x.quality)}, ${q(x.source)})`,
  ).join(",\n");
  return `-- GENERATED by scripts/gen-actuarial-migration.ts from src/lib/actuarial-db/registry.ts. Do not edit by hand.
-- 73 logical actuarial datasets (DB01–DB73) for Family Reconnect, one physical table each.
-- Run in Supabase → SQL Editor after 003_privacy.sql. RLS is on with no policies: only the server (service_role) reads and writes.

create table if not exists public.actuarial_datasets (
  dataset_id text primary key check (dataset_id ~ '^DB[0-9]{2}$'),
  table_name text not null unique,
  name text not null,
  group_id char(1) not null,
  version text not null,
  quality text not null,
  source text not null,
  updated_at timestamptz not null default now()
);
alter table public.actuarial_datasets enable row level security;

${ordered.map(tableDdl).join("\n\n")}

insert into public.actuarial_datasets (dataset_id, table_name, name, group_id, version, quality, source) values
${registryRows}
on conflict (dataset_id) do update set
  table_name = excluded.table_name, name = excluded.name, group_id = excluded.group_id,
  version = excluded.version, quality = excluded.quality, source = excluded.source, updated_at = now();

revoke all on all tables in schema public from anon, authenticated;
`;
}
